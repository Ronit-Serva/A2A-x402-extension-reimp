import assert from 'node:assert/strict';
import fs from 'node:fs';
import { Message } from '@a2a-js/sdk';
import { createWalletClient, http } from 'viem';
import { generatePrivateKey, privateKeyToAccount } from 'viem/accounts';
import { ExactEvmScheme } from '@x402/evm/exact/client';
import { toClientEvmSigner } from '@x402/evm';
import { encodePaymentRequiredHeader, encodePaymentSignatureHeader } from '@x402/core/http';
import { deployment, assertDeployment, artifact } from '../packages/shared/src/local.js';
import { EXTENSION, readCard, requirements } from '../packages/shared/src/card.js';
import { statePath } from '../packages/shared/src/store.js';
import { paidFetch } from '../apps/client/src/payment.js';
import { runPaid } from '../apps/client/src/run.js';

const config = deployment();
const chain = await assertDeployment(config);
const card = await readCard(config);
const terms = requirements(config);
const headers = { 'content-type': 'application/json', 'a2a-version': '1.0', 'a2a-extensions': EXTENSION };
const makeBody = (numbers: unknown) => ({ jsonrpc: '2.0', id: crypto.randomUUID(), method: 'SendMessage', params: { message: Message.toJSON(Message.fromJSON({ messageId: crypto.randomUUID(), role: 'ROLE_USER', parts: [{ data: { numbers }, mediaType: 'application/json' }] })) } });
const health = async () => await (await fetch('http://127.0.0.1:4021/health')).json() as { executions: number };
const startExecutions = (await health()).executions;
const unpaid = await fetch('http://127.0.0.1:4021', { method: 'POST', headers, body: JSON.stringify(makeBody([2, 4, 6])) });
assert.equal(unpaid.status, 402);
assert(unpaid.headers.get('payment-required'));
const invalid = await fetch('http://127.0.0.1:4021', { method: 'POST', headers, body: JSON.stringify(makeBody([])) });
assert.equal(invalid.status, 400);
const emptyAccount = privateKeyToAccount(generatePrivateKey());
const signed = await new ExactEvmScheme(toClientEvmSigner(emptyAccount)).createPaymentPayload(2, terms);
const failed = await fetch('http://127.0.0.1:4021', { method: 'POST', headers: { ...headers, 'payment-signature': encodePaymentSignatureHeader({ x402Version: 2, accepted: terms, payload: signed.payload }) }, body: JSON.stringify(makeBody([2, 4, 6])) });
assert.equal(failed.status, 402);
assert.equal((await health()).executions, startExecutions);
for (const wrong of [{ ...terms, amount: '2000001' }, { ...terms, payTo: config.owner }]) {
  const stub = async () => new Response('{}', { status: 402, headers: { 'PAYMENT-REQUIRED': encodePaymentRequiredHeader({ x402Version: 2, resource: { url: card.supportedInterfaces[0].url }, accepts: [wrong] }) } });
  const payment = paidFetch(card, config, emptyAccount, stub as typeof fetch);
  await assert.rejects(payment.fetchPayment('http://127.0.0.1:4021'), /Challenge differs/);
  assert.equal(payment.state.signatures, 0);
}
const output = await runPaid();
assert.deepEqual(output.before, { client: '100000000', card: '0' });
assert.deepEqual(output.after, { client: '98000000', card: '2000000' });
assert.equal(output.signatures, 1);
assert.equal(output.challenges, 1);
assert.equal(output.receipt?.success, true);
assert('parts' in output.result);
assert.deepEqual(output.result.parts[0].content?.value, { count: 3, sum: 12, min: 2, max: 6, mean: 4 });
assert.equal((await health()).executions, startExecutions + 1);
const receipt = await chain.getTransactionReceipt({ hash: output.receipt!.transaction as `0x${string}` });
assert.equal(receipt.status, 'success');
const store = JSON.parse(fs.readFileSync(statePath(config, 'requests'), 'utf8'));
const trace = store.trace.filter((entry: { id: string }) => entry.id === output.requestId);
assert(trace.findIndex((entry: { event: string }) => entry.event === 'paid') < trace.findIndex((entry: { event: string }) => entry.event === 'execution'));
fs.writeFileSync('evidence/M5-result.json', JSON.stringify({ ...output, trace, gasUsed: receipt.gasUsed.toString(), unpaidExecutions: 0, invalidAndFailedExecutions: 0, wrongChallengesSignatures: 0 }, null, 2) + '\n');
const owner = createWalletClient({ account: config.owner, chain: chain.chain, transport: http(config.rpcUrl) });
let hash = await owner.writeContract({ address: config.agentCard, abi: artifact('AgentCard').abi, functionName: 'withdrawToken', args: [config.token, config.owner, 2_000_000n] });
await chain.waitForTransactionReceipt({ hash });
hash = await owner.writeContract({ address: config.token, abi: artifact('TestUSD').abi, functionName: 'mint', args: [config.client, 2_000_000n] });
await chain.waitForTransactionReceipt({ hash });
console.log(JSON.stringify({ passed: true, requestId: output.requestId, transaction: output.receipt?.transaction, before: output.before, after: output.after, fixtureRestored: true }, null, 2));
